"""매장 사진을 인스타그램용(1080x1080) 사진으로 바꾸고 로고를 넣고, 홍보 문구도 만드는 프로그램."""
import re
from datetime import date
from pathlib import Path

from PIL import Image, ImageFilter, ImageOps

이모지 = "☕"  # 인스타그램 문구 끝에 붙는 이모지 1개

폴더 = Path(__file__).parent
자료폴더 = 폴더 / "자료"
완성폴더 = 폴더 / "완성"
로고파일 = 자료폴더 / "로고.png"

크기 = 1080
로고_비율 = 0.15   # 로고 가로 길이 = 사진 가로의 15%
로고_진하기 = 0.85  # 1이면 완전 불투명, 낮을수록 투명
로고_여백 = 40     # 사진 가장자리에서 떨어지는 거리


def 정사각형으로(사진):
    """가운데를 기준으로 정사각형으로 자르고 1080x1080으로 맞춘다(찌그러짐 없음)."""
    사진 = ImageOps.exif_transpose(사진).convert("RGB")
    return ImageOps.fit(사진, (크기, 크기), Image.LANCZOS, centering=(0.5, 0.5))


def 로고_넣기(사진, 로고):
    내용 = 로고.getchannel("A").point(lambda a: 255 if a > 20 else 0).getbbox()
    if 내용:
        로고 = 로고.crop(내용)  # 로고 주변의 빈 여백을 잘라낸다
    너비 = int(크기 * 로고_비율)
    높이 = int(로고.height * 너비 / 로고.width)
    작은로고 = 로고.resize((너비, 높이), Image.LANCZOS)
    위치 = (크기 - 너비 - 로고_여백, 크기 - 높이 - 로고_여백)
    사진 = 사진.convert("RGBA")
    # 로고 모양만 남기고 흰색으로 칠한 뒤 살짝 투명하게 만든다(사진에 스며드는 느낌)
    모양 = 작은로고.getchannel("A").point(lambda a: int(a * 로고_진하기))
    흰로고 = Image.new("RGBA", 작은로고.size, (255, 255, 255, 0))
    흰로고.putalpha(모양)
    # 밝은 사진에서도 읽히도록 아주 옅은 그림자를 먼저 깐다
    그림자 = Image.new("RGBA", 사진.size, (0, 0, 0, 0))
    그림자모양 = 모양.point(lambda a: int(a * 0.5))
    그림자조각 = Image.new("RGBA", 작은로고.size, (0, 0, 0, 0))
    그림자조각.putalpha(그림자모양)
    그림자.paste(그림자조각, (위치[0] + 1, 위치[1] + 2))
    그림자 = 그림자.filter(ImageFilter.GaussianBlur(3))
    사진.alpha_composite(그림자)
    사진.alpha_composite(흰로고, 위치)
    return 사진.convert("RGB")


def 가게정보_읽기():
    """'가게 정보.txt'를 읽어서 필요한 내용을 뽑아낸다. 파일이 없으면 None."""
    후보 = [자료폴더 / "가게 정보.txt", 자료폴더 / "가게정보.txt",
            폴더 / "가게 정보.txt", 폴더 / "가게정보.txt"]
    파일 = next((p for p in 후보 if p.exists()), None)
    if 파일 is None:
        return None

    내용 = {}
    홍보 = []
    홍보중 = False
    for 줄 in 파일.read_text(encoding="utf-8-sig").splitlines():
        줄 = 줄.strip()
        if 줄.startswith("-") and 홍보중:
            홍보.append(줄.lstrip("- ").strip())
        elif ":" in 줄:
            항목, _, 값 = 줄.partition(":")
            항목, 값 = 항목.strip(), 값.strip()
            홍보중 = 항목.endswith("홍보할 것")
            if 값:
                내용[항목] = 값

    가게 = {
        "이름": 내용.get("가게 이름", "우리 가게"),
        "위치": 내용.get("위치", ""),
        "특징": [t.strip() for t in 내용.get("가게 특징", "").split(",") if t.strip()],
        "고객층": 내용.get("주 고객층", ""),
        "메뉴": None,
        "이벤트": None,
    }
    for 항목 in 홍보:
        메뉴 = re.search(r"['\"‘“]([^'\"’”]+)['\"’”]\s*([\d,]+원)(.*)", 항목)
        if 메뉴 and 가게["메뉴"] is None:
            설명 = [t.strip(" ,") for t in 메뉴.group(3).split(",") if t.strip(" ,")]
            가게["메뉴"] = {"이름": 메뉴.group(1), "가격": 메뉴.group(2), "설명": 설명}
        elif not 메뉴 and 가게["이벤트"] is None:
            가게["이벤트"] = 항목
    return 가게


def 해시태그_만들기(가게):
    """지역 + 업종 + 메뉴를 섞어서 해시태그 10개를 만든다."""
    지역 = [w for w in 가게["위치"].split() if w != "지구"]
    태그 = [f"{w}카페" for w in 지역]                       # 지역 + 업종
    태그.append(가게["이름"].replace(" ", ""))
    if any("스페셜티" in t for t in 가게["특징"]):
        태그.append("스페셜티커피")
    if any("로스팅" in t for t in 가게["특징"]):
        태그.append("직접로스팅")
    if 가게["메뉴"]:                                         # 메뉴
        이름 = 가게["메뉴"]["이름"].replace(" ", "")
        태그 += [이름, 이름.split("라떼")[0] if "라떼" in 이름 else 이름, "신메뉴"]
    if 가게["이벤트"]:
        할인 = re.search(r"(\S+)\s+[\d,]+원\s*할인", 가게["이벤트"])
        if 할인:
            태그.append(할인.group(1) + "할인")
    태그 += ["카페스타그램", "커피맛집", "오늘의커피", "직장인카페", "혼카페"]  # 모자랄 때 채움
    결과 = []
    for t in 태그:
        if t and t not in 결과:
            결과.append(t)
    return " ".join("#" + t for t in 결과[:10])


def 조사(말, 받침있을때, 받침없을때):
    """마지막 글자에 받침이 있는지 보고 은/는, 이/가 같은 조사를 골라 준다."""
    마지막 = 말.strip()[-1]
    if "가" <= 마지막 <= "힣":
        return 받침있을때 if (ord(마지막) - ord("가")) % 28 else 받침없을때
    return 받침없을때


def 문장으로(조각):
    """'넣음', '달지 않음', '조용한 1인 좌석 많음' 같은 메모를 '~습니다' 문장으로 바꾼다."""
    조각 = 조각.strip(" .")
    많음 = re.search(r"(\S+)\s+(많음|있음|없음)$", 조각)
    if 많음:
        단어 = 많음.group(1)
        return f"{조각[:많음.start()]}{단어}{조사(단어, '이', '가')} {많음.group(2)[:-1]}습니다."
    if 조각.endswith("넣음"):
        return 조각[:-2] + "넣었습니다."
    if 조각.endswith("음"):
        return 조각[:-1] + "습니다."
    if 조각.endswith("할인") or 조각.endswith("함"):
        return 조각 + ("합니다." if 조각.endswith("할인") else "니다.")
    return 조각 + "입니다."


def 문구_만들기(가게):
    """인스타그램 문구 3가지. 사장님 말투: '~습니다', 짧은 문장, 한 줄에 한 문장, 이모지는 끝에 1개."""
    이름, 위치 = 가게["이름"], 가게["위치"]
    메뉴, 이벤트 = 가게["메뉴"], 가게["이벤트"]
    특징문장 = [문장으로(t) for t in 가게["특징"]]
    메뉴이름 = f"'{메뉴['이름']}'" if 메뉴 else ""
    메뉴문장 = [문장으로(t) for t in 메뉴["설명"]] if 메뉴 else []
    이벤트문장 = 문장으로(이벤트) if 이벤트 else ""

    감성 = [f"{이름}{조사(이름, '은', '는')} {위치}에 있습니다."] + 특징문장
    if 메뉴:
        감성 += ["", f"이번 주 신메뉴는 {메뉴이름}입니다."] + 메뉴문장
    감성[-1] += f" {이모지}"

    정보 = []
    if 메뉴:
        정보 += [f"신메뉴 {메뉴이름}를 시작합니다."] + 메뉴문장 + [f"{메뉴['가격']}입니다."]
    if 이벤트:
        정보 += ["", 이벤트문장]
    정보 += ["", f"위치는 {위치}입니다. {이모지}"]

    이벤트형 = []
    if 이벤트:
        이벤트형 += [이벤트문장, "이른 시간에 오시는 분께 드리는 할인입니다.", ""]
    if 메뉴:
        이벤트형 += [f"신메뉴 {메뉴이름}도 있습니다.", f"{메뉴['가격']}입니다."]
    이벤트형 += ["", f"{이름}입니다. {이모지}"]

    return [("감성형", "\n".join(감성)), ("정보형", "\n".join(정보)), ("이벤트형", "\n".join(이벤트형))]


def 블로그_문구(가게):
    """네이버 블로그용 긴 글(1000자 안팎, 해시태그·이모지 없음). 사장님 말투, 가게 정보에 있는 내용만 쓴다."""
    이름, 위치 = 가게["이름"], 가게["위치"]
    메뉴, 이벤트 = 가게["메뉴"], 가게["이벤트"]
    제목 = f"[{이름}] 이번 주 소식" + (f" - 신메뉴 '{메뉴['이름']}'" if 메뉴 else "")

    글 = [제목, "",
          "이번 주 소식을 전합니다.",
          "신메뉴 소식과 아침 시간 할인 안내입니다." if 메뉴 and 이벤트 else "이번 주에 알려 드릴 내용입니다.",
          "", "",
          "■ 저희 가게는",
          f"{이름}{조사(이름, '은', '는')} {위치}에 있습니다."]
    글 += [문장으로(t) for t in 가게["특징"]]
    if 가게["고객층"]:
        글.append(f"주로 {가게['고객층']}께서 찾아 주십니다.")
    글 += ["", ""]

    if 메뉴:
        글 += [f"■ 이번 주 신메뉴 '{메뉴['이름']}'",
               f"이번 주부터 '{메뉴['이름']}'를 시작합니다.",
               f"가격은 {메뉴['가격']}입니다."]
        글 += [문장으로(t) for t in 메뉴["설명"]]
        글 += ["처음 드시는 분도 계실 것 같습니다.",
               "드셔 보시고 입맛에 맞으셨는지 편하게 말씀해 주시면 반영하겠습니다.", "", ""]

    if 이벤트:
        글 += ["■ 아침 시간 할인",
               "이른 시간에 오시는 분께 드리는 할인입니다.",
               문장으로(이벤트),
               "오전에 잠깐 들러 한 잔 하고 가시기에 좋은 시간입니다.", "", ""]

    추천 = []
    if any("조용" in t for t in 가게["특징"]):
        추천.append("조용한 자리에서 혼자 쉬고 싶으신 분")
    if 메뉴 and any("달지 않" in t for t in 메뉴["설명"]):
        추천.append("달지 않고 고소한 음료를 좋아하시는 분")
    if any("스페셜티" in t or "로스팅" in t for t in 가게["특징"]):
        추천.append("직접 로스팅한 커피 맛이 궁금하신 분")
    if 이벤트:
        추천.append("오전에 잠깐 들러 한 잔 하고 싶으신 분")
    if 추천:
        글 += ["■ 이런 분께 맞습니다"] + [f"- {t}" for t in 추천] + ["", ""]

    글 += ["■ 찾아오시는 길",
           f"{위치}입니다.",
           "근처에 오실 일이 있으시면 들러 주십시오.",
           "앉아서 쉬다 가셔도 되고, 한 잔만 받아 가셔도 됩니다.", "", ""]

    글 += ["■ 한눈에 정리"]
    if 메뉴:
        글.append(f"- 신메뉴: '{메뉴['이름']}' {메뉴['가격']}")
    if 이벤트:
        글.append(f"- 할인: {이벤트}")
    글 += [f"- 위치: {위치}", "",
           "과장 없이 한 잔씩 정성껏 준비하겠습니다.",
           "끝까지 읽어 주셔서 감사합니다."]
    return "\n".join(글)


def 카톡_문구(가게):
    """카카오톡 단골 공지용: 3줄 이내, 존댓말, 이모지 없음."""
    메뉴, 이벤트 = 가게["메뉴"], 가게["이벤트"]
    줄 = [f"{가게['이름']}입니다."]
    if 메뉴:
        줄.append(f"이번 주 신메뉴 '{메뉴['이름']}'를 시작합니다. {메뉴['가격']}입니다.")
    if 이벤트:
        줄.append(문장으로(이벤트))
    return "\n".join(줄[:3])


def 문구_저장():
    가게 = 가게정보_읽기()
    if 가게 is None:
        print("'가게 정보.txt' 파일이 없어서 홍보 문구는 건너뜁니다.")
        return
    블로그 = 블로그_문구(가게)
    카톡 = 카톡_문구(가게)
    줄 = ["━━━━━ 【인스타그램용】 ━━━━━", ""]
    for 제목, 글 in 문구_만들기(가게):
        줄 += [f"■ {제목}  ({len(글)}자)", 글, ""]
    줄 += ["■ 해시태그", 해시태그_만들기(가게), ""]
    줄 += ["", f"━━━━━ 【네이버 블로그용】 ({len(블로그)}자) ━━━━━", "", 블로그, ""]
    줄 += ["", "━━━━━ 【카카오톡 단골 공지용】 ━━━━━", "", 카톡, ""]
    (완성폴더 / "홍보문구.txt").write_text("\n".join(줄), encoding="utf-8-sig")  # 메모장 등에서도 한글이 안 깨지게
    print("홍보 문구를 '완성' 폴더의 '홍보문구.txt'에 저장했습니다.")


def main():
    완성폴더.mkdir(exist_ok=True)
    문구_저장()
    사진_처리()


def 사진_처리():
    로고 =Image.open(로고파일).convert("RGBA") if 로고파일.exists() else None
    if 로고 is None:
        print("로고.png 파일이 없어서 로고 없이 만듭니다.")

    파일들 = sorted(
        p for p in 자료폴더.iterdir()
        if p.suffix.lower() in (".jpg", ".jpeg", ".png") and p != 로고파일
    )
    if not 파일들:
        print("'자료' 폴더에 사진이 없습니다.")
        return

    오늘 = date.today().strftime("%Y%m%d")
    번호 = len(list(완성폴더.glob(f"{오늘}_*.jpg")))  # 같은 날 또 실행해도 덮어쓰지 않음

    for 파일 in 파일들:
        번호 += 1
        with Image.open(파일) as 원본:
            결과 = 정사각형으로(원본)
        if 로고 is not None:
            결과 = 로고_넣기(결과, 로고)
        저장이름 = 완성폴더 / f"{오늘}_{번호:02d}.jpg"
        결과.save(저장이름, "JPEG", quality=95)
        print(f"{파일.name} -> {저장이름.name}")

    print(f"끝! {len(파일들)}장을 '완성' 폴더에 저장했습니다.")


if __name__ == "__main__":
    main()
